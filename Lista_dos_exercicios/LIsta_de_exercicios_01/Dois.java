public class Dois {
    public static void main(String[] args) {
        // 1. Declaração da variável inteira
        int numero = 17;

        // 2. Operador módulo (%) verifica o resto da divisão por 2
        if (numero % 2 == 0) {
            System.out.println("O número " + numero + " é PAR.");
        } else {
            System.out.println("O número " + numero + " é ÍMPAR.");
        }
    }
}
